-- Fresh-database schema for the repository's current C++ persistence layer.
-- Run only against a newly created, empty application database.
-- No DROP, TRUNCATE, or data replacement statements are used here.

CREATE TABLE IF NOT EXISTS branches (
    branch_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_name varchar NOT NULL,
    city varchar NOT NULL,
    address text NOT NULL
);

CREATE TABLE IF NOT EXISTS users (
    user_id varchar PRIMARY KEY,
    name varchar NOT NULL,
    email varchar NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar NOT NULL CHECK (role IN ('CUSTOMER', 'ADMIN')),
    membership_level varchar DEFAULT 'Regular',
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehicles (
    vehicle_id varchar PRIMARY KEY,
    brand varchar NOT NULL,
    model varchar NOT NULL,
    vehicle_type varchar NOT NULL,
    daily_rate numeric(12,2) NOT NULL CHECK (daily_rate > 0),
    is_available boolean NOT NULL DEFAULT TRUE,
    branch_id integer REFERENCES branches(branch_id)
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id varchar PRIMARY KEY,
    customer_id varchar NOT NULL REFERENCES users(user_id),
    vehicle_id varchar NOT NULL REFERENCES vehicles(vehicle_id),
    start_date date NOT NULL,
    end_date date NOT NULL,
    status varchar NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS rentals (
    rental_id varchar PRIMARY KEY,
    booking_id varchar NOT NULL UNIQUE REFERENCES bookings(booking_id),
    planned_return_date date NOT NULL,
    actual_return_date date,
    daily_late_fee numeric(12,2) NOT NULL CHECK (daily_late_fee >= 0)
);

CREATE TABLE IF NOT EXISTS payments (
    payment_id varchar PRIMARY KEY,
    booking_id varchar NOT NULL REFERENCES bookings(booking_id),
    amount numeric(12,2) NOT NULL CHECK (amount > 0),
    payment_method varchar NOT NULL,
    payment_status varchar NOT NULL
        CHECK (payment_status IN ('Pending', 'Successful', 'Failed'))
);

CREATE TABLE IF NOT EXISTS invoices (
    invoice_id varchar PRIMARY KEY,
    booking_id varchar NOT NULL REFERENCES bookings(booking_id),
    subtotal numeric(12,2) NOT NULL CHECK (subtotal > 0),
    discount numeric(12,2) NOT NULL DEFAULT 0 CHECK (discount >= 0),
    tax numeric(12,2) NOT NULL DEFAULT 0 CHECK (tax >= 0),
    total_amount numeric(12,2) NOT NULL CHECK (total_amount > 0),
    email_status varchar NOT NULL DEFAULT 'PENDING'
        CONSTRAINT invoices_email_status_check
        CHECK (email_status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')),
    email_attempts integer NOT NULL DEFAULT 0
        CONSTRAINT invoices_email_attempts_check CHECK (email_attempts >= 0),
    email_last_attempt_at timestamp with time zone,
    email_sent_at timestamp with time zone,
    email_last_error text
);

CREATE TABLE IF NOT EXISTS audit_logs (
    log_id varchar PRIMARY KEY,
    user_id varchar NOT NULL,
    action varchar NOT NULL,
    description text NOT NULL,
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS maintenance_records (
    maintenance_id varchar PRIMARY KEY,
    vehicle_id varchar NOT NULL REFERENCES vehicles(vehicle_id),
    service_date date NOT NULL,
    description text NOT NULL,
    status varchar NOT NULL CHECK (status IN ('SCHEDULED', 'COMPLETED')),
    maintenance_cost numeric(12,2) NOT NULL CHECK (maintenance_cost > 0),
    completion_date date,
    CHECK (completion_date IS NULL OR completion_date >= service_date),
    CHECK ((status = 'SCHEDULED' AND completion_date IS NULL) OR
           (status = 'COMPLETED' AND completion_date IS NOT NULL))
);

-- Lookup indexes. BookingRepository serializes the overlap check by locking
-- the selected vehicle row; this composite index supports the date predicate.
CREATE INDEX IF NOT EXISTS idx_vehicles_available_type
    ON vehicles (is_available, vehicle_type);
CREATE INDEX IF NOT EXISTS idx_bookings_customer_start
    ON bookings (customer_id, start_date DESC);
CREATE INDEX IF NOT EXISTS idx_bookings_vehicle_dates
    ON bookings (vehicle_id, start_date, end_date)
    WHERE status <> 'CANCELLED';
CREATE INDEX IF NOT EXISTS idx_payments_booking_status
    ON payments (booking_id, payment_status);
CREATE UNIQUE INDEX IF NOT EXISTS ux_invoices_booking_id
    ON invoices (booking_id);
CREATE INDEX IF NOT EXISTS idx_invoices_email_status
    ON invoices (email_status, email_last_attempt_at);
CREATE INDEX IF NOT EXISTS idx_maintenance_vehicle_date
    ON maintenance_records (vehicle_id, service_date DESC);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
    ON audit_logs (created_at DESC);

